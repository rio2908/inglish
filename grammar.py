FORM_QUESTIONS = {
    "is": ("She", "happy.", "Она рада."),
    "are": ("They", "happy.", "Они рады."),
    "has": ("He", "a dog.", "У него есть собака."),
    "have": ("We", "a ball.", "У нас есть мяч."),
}
FORM_CHOICES = {"is": ("is", "are", "have"), "are": ("are", "is", "has"),
                "has": ("has", "have", "are"), "have": ("have", "has", "is")}


def form_choices(word_id, rng=None):
    if word_id not in FORM_CHOICES:
        return None
    result = list(FORM_CHOICES[word_id])
    (rng or random).shuffle(result)
    return result
